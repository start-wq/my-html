-- 在 Supabase Dashboard → SQL Editor 中执行一次。
create table if not exists public.match_records (
  id bigint generated by default as identity primary key,
  room_code text not null check (char_length(room_code) between 6 and 40),
  player_id text not null check (player_id in ('clash', 'jungle', 'mid', 'farm', 'roam')),
  result text not null check (result in ('win', 'loss')),
  rating numeric(4,1) not null check (rating between 0 and 16),
  hero text,
  played_at timestamptz not null default now()
);

alter table public.match_records enable row level security;

-- RLS 策略决定“哪些行可以访问”；GRANT 决定 anon 浏览器角色是否能访问该表。
grant select, insert, delete on table public.match_records to anon;
grant usage, select on sequence public.match_records_id_seq to anon;

create policy "room members can read records" on public.match_records
for select to anon using (true);
create policy "room members can add records" on public.match_records
for insert to anon with check (true);
create policy "room members can delete records" on public.match_records
for delete to anon using (true);

create index if not exists match_records_room_played_at on public.match_records(room_code, played_at desc);

-- 惩罚金额抽取记录：同一房间的成员可共同查看。
create table if not exists public.penalty_draws (
  id bigint generated by default as identity primary key,
  room_code text not null check (char_length(room_code) between 6 and 40),
  amount numeric(4,2) not null check (amount between 0.01 and 0.10),
  drawn_at timestamptz not null default now()
);

alter table public.penalty_draws enable row level security;
grant select, insert on table public.penalty_draws to anon;
grant usage, select on sequence public.penalty_draws_id_seq to anon;

create policy "room members can read penalty draws" on public.penalty_draws
for select to anon using (true);
create policy "room members can add penalty draws" on public.penalty_draws
for insert to anon with check (true);

create index if not exists penalty_draws_room_drawn_at on public.penalty_draws(room_code, drawn_at desc);
